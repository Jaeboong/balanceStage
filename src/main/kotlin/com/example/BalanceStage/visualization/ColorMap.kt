package com.example.BalanceStage.visualization

/**
 * 등고선 시각화를 위한 컬러맵 타입
 *
 * 각 컬러맵은 0.0(최소값) ~ 1.0(최대값) 범위의 정규화된 값을 색상으로 매핑합니다.
 */
enum class ColorMap {
    /**
     * Google Turbo 컬러맵
     * - 무지개 색상의 현대적 버전
     * - 지각적으로 균일하고 색맹 친화적
     * - 권장 용도: 일반적인 데이터 시각화
     */
    TURBO,

    /**
     * MATLAB Jet 컬러맵
     * - 전통적인 무지개 색상 (파랑-청록-초록-노랑-빨강)
     * - 과학 논문에서 널리 사용됨
     * - 권장 용도: 전통적인 과학/공학 데이터
     */
    JET,

    /**
     * Viridis 컬러맵
     * - 보라색-파랑-초록-노랑 그라데이션
     * - 지각적으로 균일하고 색맹 친화적
     * - 권장 용도: 출판물, 프레젠테이션
     */
    VIRIDIS,

    /**
     * Cool-Warm 컬러맵
     * - 파랑(차가움)-흰색-빨강(따뜻함) 발산형
     * - 중간값을 강조하고 양극단을 명확히 구분
     * - 권장 용도: 편차 분석, 중립값 중심 데이터
     */
    COOLWARM,

    /**
     * Spectral 컬러맵
     * - 빨강-주황-노랑-초록-파랑-보라 스펙트럼
     * - 전통적인 등고선 지도 스타일
     * - 권장 용도: 지형도, 등고선 맵
     */
    SPECTRAL,

    /**
     * Red-Yellow-Blue 컬러맵
     * - 진한 빨강-빨강-노랑-연한 파랑-진한 파랑
     * - 기상도/지형도 스타일
     * - 권장 용도: 온도, 고도, 압력 등의 물리량
     */
    RDYLBU
}
